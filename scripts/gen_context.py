#!/usr/bin/env python3
"""Describe a running Superset's dashboards as a nao project context.

Reads the REST API only. For every dashboard it writes `context/dashboards/<id>-<slug>.md` with the
real dashboard id, its charts, the datasets (tables) behind them and its native filters. Each
dataset the dashboards use also gets `context/datasets/<table>.md`. The dock iframe passes the
same dashboard id, so the agent finds the entry by searching for it: there is no id mapping.
"""

import argparse
import http.cookiejar
import json
import pathlib
import re
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
GENERATED = "<!-- Generated by scripts/gen_context.py from the Superset REST API. Do not edit. -->"


def slugify(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-") or "dashboard"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--superset", default="http://localhost:8088")
    ap.add_argument("--user", default="admin")
    ap.add_argument("--password", default="admin")
    ap.add_argument("--out", default=str(ROOT / "context"))
    a = ap.parse_args()

    api = a.superset.rstrip("/") + "/api/v1"
    opener = urllib.request.build_opener(urllib.request.HTTPCookieProcessor(http.cookiejar.CookieJar()))
    headers = {"Content-Type": "application/json"}

    def get(path: str):
        return json.load(opener.open(urllib.request.Request(api + path, headers=headers)))

    login = urllib.request.Request(
        api + "/security/login",
        data=json.dumps({"username": a.user, "password": a.password, "provider": "db"}).encode(),
        headers=headers,
    )
    headers["Authorization"] = "Bearer " + json.load(opener.open(login))["access_token"]

    out = pathlib.Path(a.out)
    (out / "dashboards").mkdir(parents=True, exist_ok=True)
    (out / "datasets").mkdir(parents=True, exist_ok=True)
    # Regenerating must not leave entries of dashboards that no longer exist.
    for old in list((out / "dashboards").glob("*.md")) + list((out / "datasets").glob("*.md")):
        old.unlink()

    dashboards = get("/dashboard/?q=" + json.dumps({"page_size": 100, "order_column": "id"}))["result"]
    datasets_seen: dict[int, dict] = {}
    index = []

    for summary in dashboards:
        did = summary["id"]
        dash = get(f"/dashboard/{did}")["result"]
        charts = get(f"/dashboard/{did}/charts")["result"]
        datasets = get(f"/dashboard/{did}/datasets")["result"]
        meta = json.loads(dash.get("json_metadata") or "{}")
        filters = meta.get("native_filter_configuration") or []
        for ds in datasets:
            datasets_seen[ds["id"]] = ds
        ds_by_id = {ds["id"]: ds for ds in datasets}

        lines = [GENERATED, "", f"# Dashboard {did}: {dash['dashboard_title']}", "",
                 f"- Dashboard id: {did}",
                 f"- Superset URL: /superset/dashboard/{did}/"]
        if dash.get("slug"):
            lines.append(f"- Slug: {dash['slug']}")
        lines += ["", "## Datasets", ""]
        for ds in sorted(datasets, key=lambda d: d["table_name"]):
            kind = "virtual (SQL)" if ds.get("kind") == "virtual" else "physical table"
            lines.append(f"- `{ds['table_name']}`, {kind}, see datasets/{ds['table_name']}.md")
        lines += ["", "## Charts", ""]
        for ch in sorted(charts, key=lambda c: c["id"]):
            ds_name = ""
            form = ch.get("form_data") or {}
            dsid = form.get("datasource", "").split("__")[0]
            if dsid.isdigit() and int(dsid) in ds_by_id:
                ds_name = f", reads `{ds_by_id[int(dsid)]['table_name']}`"
            lines.append(f"- Chart {ch['id']}: {ch['slice_name']} ({ch.get('viz_type', 'unknown')}{ds_name})")
        lines += ["", "## Native filters", ""]
        if not filters:
            lines.append("- None.")
        for f in filters:
            targets = [
                f"`{t['datasetId'] and ds_by_id.get(t['datasetId'], {}).get('table_name', t['datasetId'])}`"
                + (f".`{t['column']['name']}`" if t.get("column") else "")
                for t in f.get("targets", [])
            ]
            lines.append(f"- {f.get('name', f['id'])} ({f.get('filterType', 'unknown')})"
                         + (f" on {', '.join(targets)}" if targets else ""))
        path = out / "dashboards" / f"{did}-{slugify(dash['dashboard_title'])}.md"
        path.write_text("\n".join(lines) + "\n")
        index.append((did, dash["dashboard_title"], path.name, len(charts), len(datasets), len(filters)))

    for ds in datasets_seen.values():
        detail = get(f"/dataset/{ds['id']}")["result"]
        lines = [GENERATED, "", f"# Dataset `{detail['table_name']}`", "",
                 f"- Database: {detail['database']['database_name']}",
                 f"- Schema: {detail.get('schema') or 'default'}"]
        if detail.get("sql"):
            lines += ["- Virtual dataset defined by this SQL:", "", "```sql", detail["sql"].strip(), "```"]
        lines += ["", "## Columns", ""]
        for col in detail["columns"]:
            lines.append(f"- `{col['column_name']}` ({col.get('type') or 'unknown'})"
                         + (f": {col['description']}" if col.get("description") else ""))
        lines += ["", "## Metrics", ""]
        metrics = detail.get("metrics") or []
        for m in metrics:
            lines.append(f"- `{m['metric_name']}`: `{m['expression']}`")
        if not metrics:
            lines.append("- None.")
        (out / "datasets" / f"{detail['table_name']}.md").write_text("\n".join(lines) + "\n")

    rows = ["| id | title | charts | datasets | filters |", "|---|---|---|---|---|"]
    rows += [f"| {i} | [{t}](dashboards/{p}) | {c} | {d} | {f} |" for i, t, p, c, d, f in index]
    (out / "dashboards" / "INDEX.md").write_text(GENERATED + "\n\n# Superset dashboards\n\n" + "\n".join(rows) + "\n")
    print(f"{len(index)} dashboards, {len(datasets_seen)} datasets -> {out}")


if __name__ == "__main__":
    main()
